<?php
/* ==========================================================
 * ログ削除ハウスキーパーバッチ
 * ----------------------------------------------------------
 * ・古いログファイルを削除するハウスキーパーバッチ
 * ・CRONで定期的に実行する想定
 * ・30日以上前のログファイルを削除
 * ・ローテーションでも良かったが、容量が少ないので
 * ----------------------------------------------------------
 * 更新履歴：
 * 2026-03-19 作成
 * ========================================================== */

/* ==========================================================
 * 定数定義
 * ========================================================== */
// 1. ログ保持日数
const RETENTION_DAYS = 30;
// 2. 削除対象のログディレクトリ
const LOG_DIRS = [
    __DIR__ . '/../Log/Info/',
    __DIR__ . '/../Log/Error/',
];
// 3. ログ保持日数を超える日付の閾値
$THRES_HOLD_DATE = new DateTime("-" . RETENTION_DAYS . " days");

/* ==========================================================
 * グローバル定義
 * ========================================================== */
// 1. 削除件数
$DeletedCount = 0;
// 2. エラー件数
$ErrorCount = 0;

/* ==========================================================
 * 処理部
 * ========================================================== */
foreach (LOG_DIRS as $LogDir) {
    /* ------------------------------
     * 1. ディレクトリが存在しない場合
     * ------------------------------*/
    if (!is_dir($LogDir)) {
        // 1. スキップ
        continue;
    }

    /* ------------------------------
     * 2. ログファイルの取得
     * ------------------------------*/
    // 1. ログファイルを取得
    $Files = glob($LogDir . '*.log');

    /* ------------------------------
     * 3. ログファイルの削除
     * ------------------------------*/
    foreach ($Files as $FilePath) {
        /* 1. ファイル名から日付を抽出 */
        if (!preg_match('/(\d{8})\.log$/', basename($FilePath), $Matches)) {
            // 1. 抽出が行えなかった場合はスキップ
            continue;
        }

        /* 2. 日付の作成 */
        // 1. DateTimeオブジェクトから日付を作成
        $FileDate = DateTime::createFromFormat('Ymd', $Matches[1]);

        /* 3. 日付が存在しない場合 */
        if ($FileDate === false) {
            // 1. スキップ
            continue;
        }

        /* 4. 削除条件の判定 */
        if ($FileDate < $THRES_HOLD_DATE) {
            /* ファイルの削除 */
            if (unlink($FilePath)) {
                // 1. 削除件数のインクリメント
                $DeletedCount++;
                // 2. 削除ログの出力
                echo "[削除] {$FilePath}\n";
            
            /* ファイル削除失敗 */
            } else {
                // 1 . エラー件数のインクリメント
                $ErrorCount++;
                // 2. エラーログの出力
                echo "[失敗] {$FilePath}\n";
            }
        }
    }
}

/* ==========================================================
 * 終了時
 * ========================================================== */
// 1. 結果の出力
echo "\n完了: {$DeletedCount}件削除, {$ErrorCount}件失敗\n";
