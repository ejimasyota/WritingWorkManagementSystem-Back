<?php
/* ==========================================================
 * 参加トークンハウスキーパーバッチ
 * ----------------------------------------------------------
 * ・有効期限がシステム日時より前となった一時参加URLトークン
 *   (ParticipationToken) を削除するハウスキーパーバッチ
 * ・CRONで定期的に実行する想定（毎日AM4:00）
 * ----------------------------------------------------------
 * 更新履歴：
 * 2026-07-04 作成
 * ========================================================== */

/* ==========================================================
 * 各モジュール呼び出し
 * ========================================================== */
// 1. DB接続用クラス
require_once __DIR__ . '/../Common/Database.php';

/* ==========================================================
 * 処理部
 * ========================================================== */
try {
    /* ------------------------------
     * 1. DB接続
     * ------------------------------*/
    $Pdo = Database::GetConnection();

    /* ------------------------------
     * 2. 有効期限切れトークンの削除
     * ------------------------------*/
    // 1. 有効期限がシステム日時より前のレコードを削除
    $Stmt = $Pdo->prepare(
        'DELETE FROM ParticipationToken WHERE expireDate < current_timestamp(3)'
    );
    // 2. 実行
    $Stmt->execute();
    // 3. 削除件数を取得
    $DeletedCount = $Stmt->rowCount();

    /* ------------------------------
     * 3. 結果の出力
     * ------------------------------*/
    echo "完了: 有効期限切れの参加トークンを {$DeletedCount} 件削除しました\n";

/* ==========================================================
 * 例外処理
 * ========================================================== */
} catch (Exception $E) {
    // 1. エラー内容を標準エラーへ出力（CRONログに残す）
    fwrite(
        STDERR,
        '参加トークン削除バッチでエラーが発生しました: ' . $E->getMessage() . "\n"
    );
    // 2. 異常終了
    exit(1);
}
