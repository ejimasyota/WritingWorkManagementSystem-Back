<?php
/* ==========================================================
 * 作中用語一覧取得
 * ----------------------------------------------------------
 * ・作中用語一覧情報取得
 * ----------------------------------------------------------
 * 更新履歴：
 * 2026-01-16 作成
 * ========================================================== */

/* ==========================================================
 * 1. 共通モジュール読み込み
 * ========================================================== */
// 1. データベース接続クラス
require_once __DIR__ . '/../Common/Database.php';
// 2. ログ出力クラス
require_once __DIR__ . '/../Common/Logger.php';
// 3. レスポンスクラス
require_once __DIR__ . '/../Common/Response.php';
require_once __DIR__ . '/../Common/Auth.php';

/* ==========================================================
 * 2. リクエストチェック
 * ========================================================== */
if ($_SERVER['REQUEST_METHOD'] !== 'GET') {
    Response::Error('不正なリクエストです', 405);
}

/* ==========================================================
 * 3. 共通定義
 * ========================================================== */
// 1. 機能名
$FunctionName = '作中用語設定';
// 2. ユーザーID
$UserId = '';

/* ==========================================================
 * 4. 処理
 * ========================================================== */
try {
   /* ---------------------------------------------
    *  1. リクエスト取得
    * --------------------------------------------- */
    // 1. 作品ID
    $WorkId = $AuthWorkId ?? '';
    // 2. ユーザーID
    $UserId = $AuthUserId;

   /* ---------------------------------------------
    *  2. 操作LOG書き込み
    * --------------------------------------------- */
    Logger::Info($FunctionName, '一覧取得処理開始', $UserId);

   /* ---------------------------------------------
    *  3. 作品IDバリデーションチェック
    * --------------------------------------------- */
    if (empty($WorkId)) {
        // 1. エラーレスポンス返却
        Response::Error('作品IDが指定されていません');
    }

   /* ---------------------------------------------
    *  4. DB接続
    * --------------------------------------------- */
    $Pdo = Database::GetConnection();

   /* ---------------------------------------------
    *  5. クエリを定義
    * --------------------------------------------- */
    $Sql = "
        SELECT
            t.termId AS \"TermId\",
            t.workId AS \"WorkId\",
            t.termName AS \"TermName\",
            t.description AS \"Description\",
            t.registDate AS \"RegistDate\",
            t.updateDate AS \"UpdateDate\",
            t.registUser AS \"RegistUser\",
            t.updateUser AS \"UpdateUser\"
        FROM TermInfo t
        WHERE t.workId = :workId
        ORDER BY t.termName ASC
    ";

   /* ---------------------------------------------
    *  6. ステートメント定義
    * --------------------------------------------- */
    $Stmt = $Pdo->prepare($Sql);

   /* ---------------------------------------------
    *  7. パラメータ設定
    * --------------------------------------------- */
    $Stmt->bindValue(':workId', $WorkId);

   /* ---------------------------------------------
    *  8. 実行
    * --------------------------------------------- */
    $Stmt->execute();

   /* ---------------------------------------------
    *  9. 一覧取得
    * --------------------------------------------- */
    $TermList = $Stmt->fetchAll();

   /* ---------------------------------------------
    *  10.操作LOG書き込み
    * --------------------------------------------- */
    Logger::Info($FunctionName, '一覧取得処理終了', $UserId);

   /* ---------------------------------------------
    *  11.レスポンス返却
    * --------------------------------------------- */
    Response::Success([
        'TermList' => $TermList,
        'TotalCount' => count($TermList)
    ]);

/* ==========================================================
 * 5. 例外処理
 * ========================================================== */
} catch (Exception $E) {
    // 1. エラーLOG書き込み
    Logger::Error($FunctionName, '一覧取得処理エラー', $UserId, $E->getMessage());
    // 2. エラーレスポンス返却
    Response::Error('作中用語一覧の取得に失敗しました');
}
