<?php
/* ==========================================================
 * 作品ロック状態更新（管理者用）
 * ----------------------------------------------------------
 * ・管理者が作品のロック状態を更新する
 * ----------------------------------------------------------
 * 更新履歴：
 * 2026-01-16 作成
 * ========================================================== */

/* ==========================================================
 * 1. 共通モジュール読み込み
 * ========================================================== */
// 1. データベース接続クラス
require_once __DIR__ . '/../Common/Database.php';
// 2. ログ出力クラス
require_once __DIR__ . '/../Common/Logger.php';
// 3. レスポンスクラス
require_once __DIR__ . '/../Common/Response.php';
require_once __DIR__ . '/../Common/Auth.php';

/* ==========================================================
 * 2. リクエストチェック
 * ========================================================== */
if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    Response::Error('不正なリクエストです', 405);
}

/* ==========================================================
 * 3. 共通定義
 * ========================================================== */
// 1. 機能名
$FunctionName = '作品一覧管理';
// 2. ユーザーID
$UserId = '';

/* ==========================================================
 * 4. 処理
 * ========================================================== */
try {
   /* ---------------------------------------------
    *  1. リクエスト取得
    * --------------------------------------------- */
    $Input = Response::GetJsonInput();

   /* ---------------------------------------------
    *  2. リクエスト内容定義
    * --------------------------------------------- */
    // 1. 作品ID
    $WorkId  = $Input['WorkId'] ?? '';
    // 2. ロックフラグ
    $LockFlg = $Input['LockFlg'] ?? false;
    // 3. 更新日時（排他制御用）
    $UpdateDate = $Input['UpdateDate'] ?? null;
    // 4. ユーザーID
    $UserId = $AuthUserId;

   /* ---------------------------------------------
    *  3. 操作ログ出力
    * --------------------------------------------- */
    Logger::Info($FunctionName, 'ロック状態更新処理開始', $UserId);

   /* ---------------------------------------------
    *  4. バリデーションチェック
    * --------------------------------------------- */
    if (empty($WorkId)) {
        Response::Error('作品IDが指定されていません');
    }

   /* ---------------------------------------------
    *  5. DB接続
    * --------------------------------------------- */
    $Pdo = Database::GetConnection();

   /* ---------------------------------------------
    *  6. 管理者権限チェック
    * --------------------------------------------- */
    $AuthSql = "SELECT 1 FROM AdminInfo WHERE userId = :userId";
    $AuthStmt = $Pdo->prepare($AuthSql);
    $AuthStmt->bindValue(':userId', $UserId, PDO::PARAM_STR);
    $AuthStmt->execute();
    $AuthRow = $AuthStmt->fetch();

    if (!$AuthRow) {
        Response::Error('管理者権限がありません', 403);
    }

   /* ---------------------------------------------
    *  7. トランザクション開始
    * --------------------------------------------- */
    Database::BeginTransaction();

   /* ---------------------------------------------
    *  8. 更新処理
    * --------------------------------------------- */
    $Sql = "
        UPDATE WorkInfo SET
            projectLockFlg = :projectLockFlg,
            updateDate = CURRENT_TIMESTAMP(3),
            updateUser = :updateUser
        WHERE workId = :workId
          AND updateDate = :updateDate
    ";
    $Stmt = $Pdo->prepare($Sql);
    $Stmt->bindValue(':workId',         $WorkId,  PDO::PARAM_STR);
    $Stmt->bindValue(':projectLockFlg', $LockFlg, PDO::PARAM_BOOL);
    $Stmt->bindValue(':updateUser',     $UserId,  PDO::PARAM_STR);
    $Stmt->bindValue(':updateDate',     $UpdateDate, PDO::PARAM_STR);
    $Stmt->execute();

    if ($Stmt->rowCount() === 0) {
        Database::Rollback();
        Response::ConflictError();
    }

   /* ---------------------------------------------
    *  9. トランザクションをコミット
    * --------------------------------------------- */
    Database::Commit();

   /* ---------------------------------------------
    *  10.操作ログ書き込み
    * --------------------------------------------- */
    $Operation = $LockFlg ? 'ロック' : 'ロック解除';
    Logger::Info($FunctionName, 'ロック状態更新処理終了: ' . $Operation, $UserId);

   /* ---------------------------------------------
    *  11.成功レスポンス
    * --------------------------------------------- */
    Response::Success([
        'Message' => '作品を' . $Operation . 'しました'
    ]);

} catch (Exception $E) {
   /* ==========================================================
    * 5. 例外処理
    * ========================================================== */
    // 1. トランザクションをロールバック
    Database::Rollback();
    // 2. エラーログ書き込み
    Logger::Error($FunctionName, 'ロック状態更新処理エラー', $UserId, $E->getMessage());
    // 3. エラーレスポンス
    Response::Error('ロック状態の更新に失敗しました');
}
