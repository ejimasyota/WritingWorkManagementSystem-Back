<?php
/* ==========================================================
 * プロジェクト削除処理
 * ----------------------------------------------------------
 * ・既存プロジェクトの削除・退出を行うAPI
 * ・作品情報テーブルの作成者とリクエストのユーザーIDが異なれば
 *   アシスタント、同一であれば作成者として扱う
 * ・作成者であれば作品情報テーブルと参加中プロジェクト・権限
 *   テーブルから削除を行う
 * ・アシスタントであれば参加中プロジェクト・権限テーブルから削除
 *   を行う
 * ----------------------------------------------------------
 * 更新履歴：
 * 2026-01-10 作成
 * 2026-01-21 利用者区分の判定ロジックを修正
 * ========================================================== */

/* ==========================================================
 * 1. 共通モジュール読み込み
 * ========================================================== */
// 1. データベース接続クラス
require_once __DIR__ . '/../Common/Database.php';
// 2. ログ出力クラス
require_once __DIR__ . '/../Common/Logger.php';
// 3. レスポンスクラス
require_once __DIR__ . '/../Common/Response.php';
require_once __DIR__ . '/../Common/Auth.php';

/* ==========================================================
 * 2. リクエストチェック
 * ========================================================== */
if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    Response::Error('不正なリクエストです', 405);
}

/* ==========================================================
 * 3. グローバル定義
 * ========================================================== */
// 1. 機能名
$FunctionName = 'プロジェクト削除';
// 2. ユーザーID
$UserId = '';

/* ==========================================================
 * 4. 処理部
 * ========================================================== */
try {
   /* ---------------------------------------------
    *  1. 定義
    * --------------------------------------------- */
    // 1. リクエスト取得
    $Input = Response::GetJsonInput();
    // 2. 作品ID
    $WorkId       = $Input['WorkId'] ?? '';
    // 3. ユーザーID
    $UserId = $AuthUserId;
    // 4. 更新年月日（排他制御用：WorkInfo）
    $UpdateDate = $Input['UpdateDate'] ?? null;
    // 5. 更新年月日（排他制御用：CreaterList）
    $CreaterUpdateDate = $Input['CreaterUpdateDate'] ?? null;

   /* ---------------------------------------------
    *  2. バリデーションチェック
    * --------------------------------------------- */
    // 1. 作品IDが存在しない場合
    if (empty($WorkId)) {
        Response::Error('作品IDが指定されていません');
    }
    // 2. ユーザーIDが存在しない場合
    if (empty($UserId)) {
        Response::Error('ユーザーIDが指定されていません');
    }

   /* ---------------------------------------------
    *  3. 開始LOG書き込み
    * --------------------------------------------- */
    Logger::Info($FunctionName, '削除処理開始', $UserId);

   /* ---------------------------------------------
    *  4. DB接続
    * --------------------------------------------- */
    $Pdo = Database::GetConnection();

   /* ---------------------------------------------
    *  5. トランザクション開始
    * --------------------------------------------- */
    Database::BeginTransaction();

   /* ---------------------------------------------
    *  6. 作成者であるかの判定
    * --------------------------------------------- */
    // 1. クエリを定義
    $CheckStmt = $Pdo->prepare('
        SELECT COUNT(*) FROM WorkInfo
        WHERE workId = :workId AND registUser = :userId
    ');
    // 2. パラメータ定義・実行
    $CheckStmt->execute([':workId' => $WorkId, ':userId' => $UserId]);
    // 3. 件数を取得
    $RowCount = (int)$CheckStmt->fetchColumn();

   /* ---------------------------------------------
    *  7. 作成者である場合
    * --------------------------------------------- */
    if (0 < $RowCount) {
        // 1. 作品情報テーブルの内容を削除するクエリを定義
        $DeleteWorkStmt = $Pdo->prepare('DELETE FROM WorkInfo WHERE workId = :workId AND updateDate = :updateDate');
        // 2. パラメータ定義・実行
        $DeleteWorkStmt->execute([':workId' => $WorkId, ':updateDate' => $UpdateDate]);
        // 3. 排他制御チェック
        if ($DeleteWorkStmt->rowCount() === 0) {
            Database::Rollback();
            Response::ConflictError();
        }

   /* ---------------------------------------------
    *  8. アシスタントである場合
    * --------------------------------------------- */
    } else {
        // 1. 参加中プロジェクト・権限テーブルの内容を削除するクエリを定義
        $DeleteCreaterStmt = $Pdo->prepare('
            DELETE FROM CreaterList
            WHERE workId = :workId AND userId = :userId AND updateDate = :updateDate
        ');
        // 2. パラメータ定義・実行
        $DeleteCreaterStmt->execute([':workId' => $WorkId, ':userId' => $UserId, ':updateDate' => $CreaterUpdateDate]);
        // 3. 排他制御チェック
        if ($DeleteCreaterStmt->rowCount() === 0) {
            Database::Rollback();
            Response::ConflictError();
        }
    }

   /* ---------------------------------------------
    *  9. トランザクションをコミット
    * --------------------------------------------- */
    Database::Commit();

   /* ---------------------------------------------
    *  10.終了LOG書き込み
    * --------------------------------------------- */
    Logger::Info($FunctionName, '削除処理終了', $UserId);

   /* ---------------------------------------------
    *  11.レスポンス返却
    * --------------------------------------------- */
    Response::Success(null, 'プロジェクトを削除しました');

/* ==========================================================
 * 5. 例外処理
 * ========================================================== */
} catch (Exception $E) {
    // 1. トランザクションをロールバック
    Database::Rollback();
    // 2. エラーLOG書き込み
    Logger::Error($FunctionName, '削除処理エラー', $UserId, $E->getMessage());
    // 3. レスポンス返却
    Response::Error('削除処理中にエラーが発生しました', 500);
}
