<?php
/* ==========================================================
 * 全ユーザー作品一覧取得（管理者用）
 * ----------------------------------------------------------
 * ・管理者が全ユーザーの作品一覧を取得する
 * ----------------------------------------------------------
 * 更新履歴：
 * 2026-01-16 作成
 * ========================================================== */

/* ==========================================================
 * 1. 共通モジュール読み込み
 * ========================================================== */
// 1. データベース接続クラス
require_once __DIR__ . '/../Common/Database.php';
// 2. ログ出力クラス
require_once __DIR__ . '/../Common/Logger.php';
// 3. レスポンスクラス
require_once __DIR__ . '/../Common/Response.php';
require_once __DIR__ . '/../Common/Auth.php';

/* ==========================================================
 * 2. リクエストチェック
 * ========================================================== */
if ($_SERVER['REQUEST_METHOD'] !== 'GET') {
    Response::Error('不正なリクエストです', 405);
}

/* ==========================================================
 * 3. 共通定義
 * ========================================================== */
// 1. 機能名
$FunctionName = '作品一覧管理';
// 2. ユーザーID
$UserId = '';

/* ==========================================================
 * 4. 処理
 * ========================================================== */
try {
   /* ---------------------------------------------
    *  1. リクエスト取得
    * --------------------------------------------- */
    // 1. ユーザーID
    $UserId = $AuthUserId;

   /* ---------------------------------------------
    *  2. 操作LOG書き込み
    * --------------------------------------------- */
    Logger::Info($FunctionName, '一覧取得処理開始', $UserId);

   /* ---------------------------------------------
    *  3. DB接続
    * --------------------------------------------- */
    $Pdo = Database::GetConnection();

   /* ---------------------------------------------
    *  4. 管理者権限チェック
    * --------------------------------------------- */
    $AuthSql = "SELECT 1 FROM AdminInfo WHERE userId = :userId";
    $AuthStmt = $Pdo->prepare($AuthSql);
    $AuthStmt->bindValue(':userId', $UserId, PDO::PARAM_STR);
    $AuthStmt->execute();
    $AuthRow = $AuthStmt->fetch();

    if (!$AuthRow) {
        Response::Error('管理者権限がありません', 403);
    }

   /* ---------------------------------------------
    *  5. クエリを定義
    * --------------------------------------------- */
    $Sql = "
        SELECT
            w.workId AS \"WorkId\",
            w.workTitle AS \"WorkName\",
            w.registUser AS \"UserId\",
            w.registUser AS \"UserName\",
            w.projectLockFlg AS \"LockFlg\",
            w.registDate AS \"RegistDate\",
            w.updateDate AS \"UpdateDate\"
        FROM WorkInfo w
        WHERE NOT EXISTS (
            SELECT 1 FROM AdminInfo a WHERE a.userId = w.registUser
        )
        ORDER BY w.registDate DESC
    ";

   /* ---------------------------------------------
    *  6. ステートメント定義・実行
    * --------------------------------------------- */
    $Stmt = $Pdo->prepare($Sql);
    $Stmt->execute();

   /* ---------------------------------------------
    *  7. 一覧取得
    * --------------------------------------------- */
    $WorkList = $Stmt->fetchAll();

   /* ---------------------------------------------
    *  8. 操作LOG書き込み
    * --------------------------------------------- */
    Logger::Info($FunctionName, '一覧取得処理終了', $UserId);

   /* ---------------------------------------------
    *  9. レスポンス返却
    * --------------------------------------------- */
    Response::Success([
        'WorkList' => $WorkList,
        'TotalCount' => count($WorkList)
    ]);

/* ==========================================================
 * 5. 例外処理
 * ========================================================== */
} catch (Exception $E) {
    // 1. エラーLOG書き込み
    Logger::Error($FunctionName, '一覧取得処理エラー', $UserId, $E->getMessage());
    // 2. エラーレスポンス返却
    Response::Error('作品一覧の取得に失敗しました');
}
